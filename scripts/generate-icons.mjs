/**
 * Generates every app icon from the favicon design:
 *  - Android adaptive icon (vector foreground + dark background, themed icon on Android 13+),
 *  - legacy launcher PNGs for Android 7.x (square and round),
 *  - Android splash screens (dark background with the icon),
 *  - web icons (apple-touch-icon, 192/512 PNGs and a maskable variant).
 *
 * Run with `npm run icons` after changing the design below.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const RES = join(ROOT, 'android/app/src/main/res')
const PUBLIC = join(ROOT, 'public')

// ----- design (same as public/favicon.svg, 64x64 units) ---------------------
const BACKGROUND = '#0a0a0f'
const ACCENT = '#2ee6d6'
const FRAME_PATH = 'M16 22h32a4 4 0 0 1 4 4v18a4 4 0 0 1-4 4H16a4 4 0 0 1-4-4V26a4 4 0 0 1 4-4z'
const PLAY_PATH = 'M28 28l14 8-14 8z'
// Visual bounds of the glyph including the stroke.
const GLYPH = { x: 10, y: 20, width: 44, height: 30 }

/** Glyph scaled so its width is `width` units and centred on (cx, cy). */
function glyph(cx, cy, width) {
  const scale = width / GLYPH.width
  const tx = cx - (GLYPH.x + GLYPH.width / 2) * scale
  const ty = cy - (GLYPH.y + GLYPH.height / 2) * scale
  return `<g transform="translate(${tx} ${ty}) scale(${scale})">
    <path d="${FRAME_PATH}" fill="none" stroke="${ACCENT}" stroke-width="4"/>
    <path d="${PLAY_PATH}" fill="${ACCENT}"/>
  </g>`
}

const svg = (w, h, body) => `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">${body}</svg>`

/** The favicon itself: rounded dark square with the glyph. */
const roundedIcon = () => svg(64, 64, `<rect width="64" height="64" rx="14" fill="${BACKGROUND}"/>${glyph(32, 35, 44)}`)
const roundIcon = () => svg(64, 64, `<circle cx="32" cy="32" r="32" fill="${BACKGROUND}"/>${glyph(32, 33, 38)}`)
/** Full-bleed square; the platform applies its own mask (iOS, maskable PWA icons). */
const fullBleedIcon = (glyphWidth) => svg(64, 64, `<rect width="64" height="64" fill="${BACKGROUND}"/>${glyph(32, 33, glyphWidth)}`)

// Adaptive icons draw on a 108dp canvas; only the central 66dp circle is safe
// from masking, so the glyph (with its rounded corners) must stay inside it.
const ADAPTIVE_GLYPH_WIDTH = 52.8
const adaptiveForeground = () => svg(108, 108, glyph(54, 54, ADAPTIVE_GLYPH_WIDTH))

async function png(svgSource, size, file) {
  await mkdir(dirname(file), { recursive: true })
  const [w, h] = Array.isArray(size) ? size : [size, size]
  // Rasterise at (at least) the target size so small SVG canvases stay sharp.
  const intrinsicWidth = Number(/width="([\d.]+)"/.exec(svgSource)?.[1] ?? w)
  await sharp(Buffer.from(svgSource), { density: 72 * Math.max(1, Math.ceil(w / intrinsicWidth)) })
    .resize(w, h)
    .png({ compressionLevel: 9 })
    .toFile(file)
}

// ----- Android ---------------------------------------------------------------
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 }

function vectorForeground() {
  const scale = ADAPTIVE_GLYPH_WIDTH / GLYPH.width
  const tx = 54 - (GLYPH.x + GLYPH.width / 2) * scale
  const ty = 54 - (GLYPH.y + GLYPH.height / 2) * scale
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-icons.mjs - do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="${tx.toFixed(3)}"
        android:translateY="${ty.toFixed(3)}"
        android:scaleX="${scale.toFixed(4)}"
        android:scaleY="${scale.toFixed(4)}">
        <path
            android:pathData="${FRAME_PATH}"
            android:fillColor="#00000000"
            android:strokeColor="${ACCENT.toUpperCase()}"
            android:strokeWidth="4" />
        <path
            android:pathData="${PLAY_PATH}"
            android:fillColor="${ACCENT.toUpperCase()}" />
    </group>
</vector>
`
}

const adaptiveXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-icons.mjs - do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
`

async function android() {
  // Vector foreground (API 24+ uses drawable-v24, so write it there).
  await writeFile(join(RES, 'drawable-v24/ic_launcher_foreground.xml'), vectorForeground())
  await writeFile(join(RES, 'mipmap-anydpi-v26/ic_launcher.xml'), adaptiveXml)
  await writeFile(join(RES, 'mipmap-anydpi-v26/ic_launcher_round.xml'), adaptiveXml)
  await writeFile(
    join(RES, 'values/ic_launcher_background.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${BACKGROUND.toUpperCase()}</color>\n</resources>\n`,
  )

  // Launcher PNGs for Android 7.x and launchers without adaptive icon support.
  for (const [name, factor] of Object.entries(DENSITIES)) {
    const dir = join(RES, `mipmap-${name}`)
    await png(roundedIcon(), Math.round(48 * factor), join(dir, 'ic_launcher.png'))
    await png(roundIcon(), Math.round(48 * factor), join(dir, 'ic_launcher_round.png'))
    await png(adaptiveForeground(), Math.round(108 * factor), join(dir, 'ic_launcher_foreground.png'))
  }

  // Splash screens: keep each file's size, repaint it dark with the icon.
  const splashFiles = ['drawable/splash.png']
  for (const orientation of ['port', 'land']) {
    for (const name of Object.keys(DENSITIES)) splashFiles.push(`drawable-${orientation}-${name}/splash.png`)
  }
  for (const rel of splashFiles) {
    const file = join(RES, rel)
    const { width, height } = await sharp(await readFile(file)).metadata()
    const glyphWidth = Math.min(width, height) * 0.28
    await png(svg(width, height, `<rect width="${width}" height="${height}" fill="${BACKGROUND}"/>${glyph(width / 2, height / 2, glyphWidth)}`), [width, height], file)
  }
}

// ----- web -------------------------------------------------------------------
async function web() {
  await png(fullBleedIcon(44), 180, join(PUBLIC, 'apple-touch-icon.png'))
  await png(roundedIcon(), 192, join(PUBLIC, 'icon-192.png'))
  await png(roundedIcon(), 512, join(PUBLIC, 'icon-512.png'))
  // Maskable icons may be cropped to a circle of 80% - keep the glyph well inside.
  await png(fullBleedIcon(36), 512, join(PUBLIC, 'icon-maskable-512.png'))
}

await android()
await web()
console.log('[clip] icons generated for Android and the web')
